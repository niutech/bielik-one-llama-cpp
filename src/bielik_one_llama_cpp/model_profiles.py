from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True, slots=True)
class ModelProfile:
    """Best-effort model identity inferred from the local GGUF filename.

    Calibration is deliberately conservative: an unknown or renamed file is
    never assumed to have the official 11B BF16 calibration profile.
    """

    family: str = "unknown"
    quantization: str = "unknown"

    @property
    def has_official_calibration(self) -> bool:
        return self.family == "11B" and self.quantization == "BF16"

    def as_dict(self) -> dict[str, str]:
        return {"family": self.family, "quantization": self.quantization}


_QUANTIZATION_PATTERNS = (
    ("Q4_K_M", re.compile(r"(?:^|[-_.])Q4_K_M(?:[-_.]|$)", re.IGNORECASE)),
    ("Q8_0", re.compile(r"(?:^|[-_.])Q8_0(?:[-_.]|$)", re.IGNORECASE)),
    ("BF16", re.compile(r"(?:^|[-_.])BF16(?:[-_.]|$)", re.IGNORECASE)),
)


def detect_model_profile(model_path: str | Path) -> ModelProfile:
    """Infer 4B/11B and Q4_K_M/Q8_0/BF16 from a Hugging Face GGUF filename."""
    name = Path(model_path).name.upper()
    family = "unknown"
    if re.search(r"(?:^|[-_.])11B(?:[-_.]|$)", name):
        family = "11B"
    elif re.search(r"(?:^|[-_.])4B(?:[-_.]|$)", name):
        family = "4B"

    quantization = "unknown"
    for label, pattern in _QUANTIZATION_PATTERNS:
        if pattern.search(name):
            quantization = label
            break
    return ModelProfile(family=family, quantization=quantization)


@dataclass(frozen=True, slots=True)
class CalibrationSelection:
    enabled: bool
    path: str | None
    source: str
    profile: ModelProfile


def resolve_auto_calibration(model_path: str | Path) -> CalibrationSelection:
    """Select only a model-matched sidecar or the official 11B BF16 profile.

    A calibration generated by ``bielik-one-llama-cpp calibrate`` is saved as
    ``<model-stem>.calibration.json`` next to the GGUF.  This makes the default
    safe for multiple models/quantizations in one directory.
    """
    path = Path(model_path)
    profile = detect_model_profile(path)

    sidecar = path.with_suffix(".calibration.json")
    if sidecar.is_file():
        return CalibrationSelection(
            enabled=True,
            path=str(sidecar),
            source="model sidecar",
            profile=profile,
        )

    if profile.has_official_calibration:
        return CalibrationSelection(
            enabled=True,
            path=None,
            source="official 11B BF16 temperatures",
            profile=profile,
        )

    return CalibrationSelection(
        enabled=False,
        path=None,
        source="no matching calibration; using raw probabilities",
        profile=profile,
    )
